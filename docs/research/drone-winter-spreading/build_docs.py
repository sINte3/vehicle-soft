def fmt(n, digits=0):
    """1800000 -> '1 800 000'; 1.8 -> '1,8'."""
    if digits == 0:
        return '{:,.0f}'.format(round(n)).replace(',', ' ')
    return ('{:,.%df}' % digits).format(n).replace(',', ' ').replace('.', ',')


def k(n):
    """Округление до тысяч для текста: 288857 -> '289 000'."""
    return fmt(round(n / 1000.0) * 1000)


