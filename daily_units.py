# -*- coding: utf-8 -*-
"""Приведение свободно набранной единицы измерения к коду справочника.

Один модуль на два потребителя, у которых нет общего предка:

* `migrate_daily_units_001.py` — миграция, stdlib и `sqlite3` без Flask;
* `app.py` — приложение, которому нужно то же самое сопоставление, чтобы
  подставить в поле выбора значение `work_types.default_unit` и
  `equipment.default_unit`. Оба справочника хранят единицу свободным текстом
  («м-соат», «Га»), а поле выбора принимает только код.

[REASON]: модуль stdlib-only и НИЧЕГО не импортирует из приложения. Его
импортирует миграция, а миграция по уставу проекта не имеет права тянуть
Flask: `from app import app` выполняет `db.create_all()` на импорте и
превращает читателя в писателя.

Карта — единственная на проект. Её совпадение с копией внутри миграции
закреплено тестом `tests/test_daily_units.py`: если кто-то добавит единицу
в одном месте и забудет в другом, тест назовёт разошедшиеся ключи.
"""

# [REASON]: сопоставление ТОЧНОЕ, по нормализованной строке целиком.
# Префиксное сравнение сопоставило бы запись на 253 символа, начинающуюся
# со слов «м-соат будем считать с 08:00-18:00», с единицей m_soat.
UNIT_ALIASES = {
    'га': 'ga', 'гектар': 'ga', 'ga': 'ga',
    'соат': 'soat', 'час': 'soat', 'часов': 'soat', 'soat': 'soat',
    'м-соат': 'm_soat', 'мотосоат': 'm_soat', 'моточас': 'm_soat',
    'м/соат': 'm_soat', 'm-soat': 'm_soat', 'm_soat': 'm_soat',
    'рейс': 'reys', 'реййс': 'reys', '1 рейс': 'reys', 'reys': 'reys',
    'тн/км': 'tn_km', 'тонна/км': 'tn_km', 'тонно-километр': 'tn_km',
    'tn/km': 'tn_km', 'tn_km': 'tn_km',
    'км': 'km', 'километр': 'km', 'km': 'km',
}

# Строка длиннее этого единицей измерения быть не может: самая длинная
# настоящая — «тонно-километр», 14 символов.
MAX_UNIT_LEN = 30

# Отправленное значение, которое надо понимать как «оставить как было».
# [REASON]: двоеточие делает префикс недостижимым для кода справочника —
# коды латинские в snake_case, двоеточия в них не бывает. Поэтому строку
# нельзя спутать с кодом ни при каком наполнении справочника.
RAW_PREFIX = 'raw:'


def normalize_unit_text(value):
    """Привести значение к виду, в котором его ищут в карте.

    Схлопывает пробелы, снимает регистр. Строку длиннее `MAX_UNIT_LEN`
    возвращает пустой: это не единица измерения, а что-то другое.
    """
    if value is None:
        return ''
    text = ' '.join(str(value).split()).strip().lower()
    return text if len(text) <= MAX_UNIT_LEN else ''


def resolve_unit_code(value, valid_codes=None):
    """Код справочника для свободно набранного значения, иначе `None`.

    `None` — это состояние «не распознано», а не пробел заполнения:
    значение, которого нет в карте, сознательно не авторегистрируется как
    новая единица (DD-004).

    `valid_codes` — набор кодов, действительно существующих в справочнике.
    Если передан, код вне набора считается нераспознанным: справочником
    управляют из интерфейса, и строку могли выключить.
    """
    code = UNIT_ALIASES.get(normalize_unit_text(value))
    if code is None:
        return None
    if valid_codes is not None and code not in valid_codes:
        return None
    return code


def is_raw_unit(submitted):
    """Отправленное значение несёт исходный нераспознанный текст."""
    return isinstance(submitted, str) and submitted.startswith(RAW_PREFIX)


def raw_unit_value(submitted):
    """Исходный текст из значения с префиксом `RAW_PREFIX`."""
    return submitted[len(RAW_PREFIX):] if is_raw_unit(submitted) else ''
