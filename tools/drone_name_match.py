# -*- coding: utf-8 -*-
"""Сопоставление кириллического имени заказчика с латинским именем контура DJI.

Диспетчер пишет в книге «Аваз Исматов фх». Оператор набирает на пульте
«avaz ismatov 1». Это один заказчик, и связать их надо не глазами, а правилом,
которое можно проверить.

Модуль только про имена: ни базы, ни отчёта, ни решения «это совпало». Он
отдаёт ключ и оценку схожести; что считать совпадением, решает вызывающий и
показывает оператору вместе с доказательством.

ПОЧЕМУ НЕ ПРОСТО ТРАНСЛИТЕРАЦИЯ. Узбекская латиница неоднозначна ровно там,
где люди пишут на слух, и в настоящих данных встречаются обе стороны каждой
пары:

    «Бухоро»    -> buxoro      (х как x)
    «Баронхужа» -> baronho'ja  (х как h)      -- одна и та же буква
    «Абдукодиробод» -> abduqodir obod         -- пробел появился
    «Шерзод Сохиб»  -> sherzodsohib2,5        -- пробел исчез, приклеена цифра
    «Заминлари»     -> zaminlari / zamjnlari  -- опечатка в одну букву

Поэтому ключ строится так: транслитерация, выброс всего, что не буква (цифр,
пробелов, апострофов -- заодно gʻ становится g, а oʻ становится o), затем
СХЛОПЫВАНИЕ пар x/h, q/k, w/v, y/i, j/i, c/s. Сравнение идёт по цельной
строке, поэтому разница в пробелах перестаёт мешать, а опечатка в один символ
ловится расстоянием Левенштейна.

ТРИ ПОЛОСЫ, А НЕ ДА/НЕТ. Оценка 0.75 и выше -- совпадение, которое можно
принимать; 0.5..0.74 -- кандидат, который обязан увидеть человек; ниже --
молчание. Средняя полоса существует не для красоты: «Норов Фахри фх» против
«Norov Bek 2» и «Пешку Сервис ери» против «Servis 4» дают ровно её -- общее
слово есть, различающего нет. Выдать такую пару за совпадение значит записать
работу чужому хозяйству.

ЧЕГО МОДУЛЬ НЕ ДЕЛАЕТ. Не решает за человека. `score` возвращает число и
причину; порог и последнее слово -- снаружи. Правило учёта из схожести имён
не выводится: совпадение имени -- повод показать строку владельцу, а не
основание переписать гектары.
"""

import re
import unicodedata

# ─── Транслитерация ───────────────────────────────────────────────────────────
#
# Узбекская кириллица плюс русские буквы, которые встречаются в книгах.
# Порядок важен: многобуквенные сначала, иначе «ч» превратится в «c»+«h».

_MULTI = (
    ('ё', 'yo'), ('ж', 'j'), ('ц', 'ts'), ('ч', 'ch'), ('ш', 'sh'),
    ('щ', 'sh'), ('ю', 'yu'), ('я', 'ya'), ('ў', "o'"), ('ғ', "g'"),
    ('қ', 'q'), ('ҳ', 'h'), ('ъ', "'"), ('ь', ''),
)

_SINGLE = {
    'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'з': 'z',
    'и': 'i', 'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n', 'о': 'o',
    'п': 'p', 'р': 'r', 'с': 's', 'т': 't', 'у': 'u', 'ф': 'f', 'х': 'x',
    'ы': 'i', 'э': 'e',
}

# [REASON]: слова-пустышки, которыми в книгах помечают форму хозяйства. Они
# есть почти в каждой строке книги и почти никогда -- в имени контура, так что
# без их выброса каждая пара теряет по общему токену и оценка проседает ровно
# там, где совпадение на самом деле полное.
_NOISE_WORDS = frozenset((
    'фх', 'ф', 'х', 'фермер', 'фермерхужалиги', 'хужалиги', 'хужалик',
    'хожалиги', 'xojaligi', 'xo', 'fermer', 'fx', 'mchj', 'мчж', 'ооо',
    'ffx', 'fermerxojaligi', 'ga', 'га', 'kb', 'кб',
))

_APOSTROPHES = "'‘’ʻʼ`´"


def translit(value):
    """Кириллица -> латиница. Латиница проходит насквозь."""
    if not value:
        return ''
    text = unicodedata.normalize('NFKC', str(value)).casefold()
    for source, target in _MULTI:
        text = text.replace(source, target)
    return ''.join(_SINGLE.get(char, char) for char in text)


# [REASON]: схлопывание пар, которые в узбекской латинице пишут и так и так.
# Каждая пара подтверждена настоящими данными сентября 2025, а не взята из
# грамматики: buxoro/baronho'ja дают x и h для одной кириллической «х»;
# qogon/kogon -- q и k; g'ijduvon/gijduvon -- g' и g. Схлопывание НЕ
# симметрично по риску: оно может склеить два разных имени, поэтому итог
# сравнивается целиком, а не по одному токену.
_FOLD = {
    'x': 'h', 'q': 'k', 'w': 'v', 'y': 'i', 'j': 'i', 'c': 's',
}


def _fold(text):
    text = ''.join(char for char in text if char.isalpha())
    return ''.join(_FOLD.get(char, char) for char in text)


def name_key(value):
    """Сравнительный ключ: только значимые буквы, неоднозначные схлопнуты.

    Пробелы, цифры, апострофы и знаки убираются полностью -- именно они и
    расходятся между книгой и пультом.

    [REASON]: слова-пустышки выбрасываются И ЗДЕСЬ, а не только в name_tokens.
    Пока «фх» оставалось в ключе, «Баронхужа 2022 фх» давало baronhuiafh
    против baronhoia контура -- разница длин в два символа, и проверка на
    опечатку обрывалась, не начавшись. Пара из настоящих данных сентября,
    которая обязана совпадать, не совпадала ни по одному правилу.
    """
    return ''.join(name_tokens(value))


_SPLIT_RE = re.compile(r'[^0-9a-zA-Zа-яёўғқҳА-ЯЁЎҒҚҲ]+')


def name_tokens(value):
    """Значимые слова имени: без цифр, без слов-пустышек, каждое -- ключом."""
    if not value:
        return []
    tokens = []
    for part in _SPLIT_RE.split(str(value)):
        if not part:
            continue
        # «behruzT1,3» и «Servis 6br 3.9»: цифры приклеены к слову.
        letters = ''.join(char for char in part if not char.isdigit())
        if not letters:
            continue
        if translit(letters).strip(_APOSTROPHES) in _NOISE_WORDS:
            continue
        # [REASON]: _fold(), не name_key() -- name_key построен НА токенах, и
        # вызов отсюда замкнул бы их друг на друга. Разрыв кольца здесь, а не
        # там, потому что токен -- это одно слово: ему нечего выбрасывать.
        key = _fold(translit(letters))
        if len(key) >= 2:
            tokens.append(key)
    return tokens


def levenshtein(left, right, cap=3):
    """Расстояние Левенштейна, оборванное на cap (дальше нам всё равно)."""
    if left == right:
        return 0
    if abs(len(left) - len(right)) > cap:
        return cap + 1
    previous = list(range(len(right) + 1))
    for i, lchar in enumerate(left, start=1):
        current = [i]
        best = i
        for j, rchar in enumerate(right, start=1):
            value = min(previous[j] + 1,
                        current[j - 1] + 1,
                        previous[j - 1] + (lchar != rchar))
            current.append(value)
            if value < best:
                best = value
        if best > cap:
            return cap + 1
        previous = current
    return previous[-1]


# Оценки. Числа -- технический выбор, не деловое правило; каждая пара
# показывается человеку вместе с причиной.
SCORE_EXACT = 1.0
SCORE_NEAR = 0.9          # опечатка в один-два символа
SCORE_PREFIX = 0.8        # одно имя -- начало другого
SCORE_TOKENS_ALL = 0.75   # все значимые слова книги нашлись в контуре
SCORE_TOKENS_BACK = 0.65  # наоборот: все слова контура нашлись в книге
SCORE_TOKENS_SOME = 0.5   # нашлась часть

# Порог, выше которого пара считается совпадением без участия человека.
SCORE_CONFIDENT = 0.75
# Ниже этого пара вообще не показывается.
SCORE_CANDIDATE = 0.5


def _typo_budget(length):
    """Сколько опечаток простительно строке такой длины."""
    if length >= 12:
        return 2
    if length >= 6:
        return 1
    return 0


def score(book_name, contour_name):
    """(оценка, причина) для пары «имя из книги» / «имя контура».

    Оценка 0.0 -- ничего общего. Причина всегда заполнена: она печатается
    рядом с парой в отчёте, чтобы совпадение можно было оспорить, не залезая
    в код.
    """
    book_key = name_key(book_name)
    contour_key = name_key(contour_name)
    if not book_key or not contour_key:
        return 0.0, 'пустое имя'

    if book_key == contour_key:
        return SCORE_EXACT, 'ключи совпали полностью'

    budget = _typo_budget(min(len(book_key), len(contour_key)))
    if budget:
        distance = levenshtein(book_key, contour_key, cap=budget)
        if distance <= budget:
            return SCORE_NEAR, 'различие в %d символ(ов)' % distance

    # [REASON]: «Чинор фх» против «Chinor fermer xojaligi 3.8» -- имя книги
    # целиком лежит в начале имени контура. Порог в 5 букв не даёт «ери» или
    # «обод» цепляться к каждому второму контуру.
    shorter, longer = sorted((book_key, contour_key), key=len)
    if len(shorter) >= 5 and longer.startswith(shorter):
        return SCORE_PREFIX, 'одно имя начинает другое'

    # [REASON]: слова короче четырёх букв («ПТЗ», «ери», «Т») выброшены из
    # ЗНАМЕНАТЕЛЯ, а не только из числителя. Пока «ПТЗ» считалось словом,
    # «Сарвари ПТЗ» против «ptz sarvari 5» давало «1 из 2» -- совпало всё, что
    # можно проверить, а оценка выглядела половинной. Короткое слово ничего не
    # доказывает ни своим наличием, ни своим отсутствием.
    book_words = [word for word in name_tokens(book_name) if len(word) >= 4]
    contour_words = [word for word in name_tokens(contour_name)
                     if len(word) >= 4]
    if not book_words:
        return 0.0, 'в имени книги нет значимых слов'

    hits = [word for word in book_words if word in contour_key]
    if hits and len(hits) == len(book_words):
        return SCORE_TOKENS_ALL, 'все слова книги есть в контуре: %s' % (
            ', '.join(hits))

    # [REASON]: обратное вложение -- оператор пишет короче диспетчера:
    # «zaminlari» вместо «Бухоро Агрокластер Заминлари». Но доказательство
    # тут СЛАБЕЕ прямого, и это видно на настоящих данных: «Norov Bek 2»
    # против «Норов Фахри фх» проходит по тому же правилу, а это разные
    # хозяйства -- различающее слово у книги есть, у контура его нет. Поэтому
    # своя оценка ниже порога уверенности: пара показывается человеку, а не
    # принимается молча. Отличить «Заминлари» от «Норов» длиной слова можно,
    # но это была бы константа, подогнанная под три примера.
    back = [word for word in contour_words if word in book_key]
    if back and len(back) == len(contour_words):
        return SCORE_TOKENS_BACK, 'все слова контура есть в книге: %s' % (
            ', '.join(back))

    if not hits:
        return 0.0, 'нет общих слов'
    return (SCORE_TOKENS_SOME,
            'совпали слова %d из %d: %s' % (len(hits), len(book_words),
                                            ', '.join(hits)))
