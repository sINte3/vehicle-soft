# -*- coding: utf-8 -*-
"""Какие объекты Wialon план-факт не считает и почему. Только stdlib.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ
Правило нужно двум разным процессам: суточному расчёту (`gps/daily.py`, живёт
в venv с numpy/shapely) и инструменту инвентаря (`tools/gps_units_inventory.py`,
запускается системным питоном сервера, где этого стека нет). Если бы правило
лежало в `daily.py`, инструмент не смог бы его импортировать -- `import numpy`
на верхнем уровне -- и завёл бы собственную копию. Две копии одного правила
расходятся молча: инструмент сказал бы владельцу «объект считается», а расчёт
его пропускал бы.

Модуль ничего не открывает и ничего не пишет: принимает готовое соединение
`sqlite3` и возвращает словарь. Ни Flask, ни `models`, ни numpy.

ТРЕТЬЯ РЕАЛИЗАЦИЯ ВСЁ РАВНО ЕСТЬ. Экран `/gps/fact` считает то же множество
через SQLAlchemy (`gps_routes._excluded_units`): служба Flask не тянет стек
`gps/`, а этот модуль не должен тянуть `models`. Две реализации закреплены
общим тестом на одной и той же базе.
"""

import sqlite3

# Категории техники, которой на план-факте быть не должно. Слаг -- значение
# `Equipment.category`, как его ведут люди на экране техники.
#
# [REASON]: владелец 27.09 попросил убрать легковые машины. «Легковая» -- это
# НЕ новый признак: категория 9 «Йўловчи ташиш техникаси» существует в
# `models.CATEGORIES` с самого начала и заполняется теми же людьми, что ведут
# технику. Брать её, а не `VialonMapping.skip`, обязательно: `skip` означает
# «не наша техника» и гасит машину ещё и в импорте моточасов --
# `wialon_import.apply_mappings` кладёт помеченные строки в `skipped`, и
# моточасы не пишутся вовсе. Это учёт соседнего трека. Легковая машина наша,
# просто поля не пашет, и трогать её моточасы нельзя.
#
# Значение продублировано, а не импортировано: `models.py` тянет Flask, а
# ничто под `gps/` его не импортирует (gps/requirements.txt). Дубль закреплён
# тестом против `models.CATEGORIES`, чтобы переименование не прошло молча.
#
# Грузовые (категория 7) внесены 28.09 по решению владельца, и решение опёрлось
# на цифры первого инвентаря: 25 грузовых объектов дали 523,6 га «обработки» за
# 30 суток -- больше, чем все высокопроизводительные машины вместе (517,2 га).
# Крупнейший ложный гектар парка -- молоковоз HYUNDAI 80 555 UBA: 354,4 га за 13
# суток при 4287 км пробега. Расчёт берёт точки в окне 1-15 км/ч, а грузовик в
# городе, на погрузке и в пробке едет именно так; альфа-форма по этим точкам
# накрывает пол-района.
#
# Категория выбрана и здесь не случайно: она исключает объект с экрана, НЕ
# трогая ни `equipment_id`, ни моточасы. Галочка «нет в системе» на экране
# сопоставления обнулила бы `equipment_id`
# (`wialon_import.py`: `m.equipment_id = eq_id if not skip else None`), а эта
# связь нужна владельцу под будущий отчёт «пробег + посещение геозон» по тем же
# бортовым машинам.
#
# ОТКРЫТО: мотоциклы (8) и спецтехника (6) сюда НЕ внесены. Про спецтехнику
# владелец 28.09 ответил определением, а не решением, и вопрос задан заново:
# 20 объектов, 208 суток, 46,8 га -- погрузчики и экскаваторы.
NON_FIELD_CATEGORIES = frozenset({"passenger", "yuk_transport"})

EXCLUDED_NOT_OURS = "ne_nasha"      # VialonMapping.skip = 1
EXCLUDED_NON_FIELD = "ne_polevaya"  # категория техники не полевая


def excluded_units(con):
    """unit_id -> почему план-факт этот объект не считает. Ничего не пишет.

    [REASON]: исключает только то, о чём человек сказал явно -- строка со
    `skip = 1` либо машина в непольевой категории. Всё остальное считается,
    потому что две ошибки не равны: посчитанный лишний объект виден на
    /gps/fact, где владелец его и увидит, а исключённый по ошибке молча теряет
    работу машины из план-факта, и на экране об этом ничего не написано.
    Поэтому строка со `skip NULL` (колонку добавляли миграцией к уже
    существующим строкам) не исключает, и объект без строки сопоставления --
    тоже: у 34 живых машин трека строки ещё нет.

    Один id может нести несколько строк -- у машины со сменёнными трекерами их
    три. Если хоть одна строка объекта говорит «считать» (не помечена, или
    ведёт на полевую категорию), объект остаётся: две строки с противоположным
    смыслом -- противоречие, которое разбирает человек
    (`tools/gps_units_inventory.py` их называет), а не этот запрос.
    """
    try:
        rows = con.execute(
            "SELECT m.wialon_id, m.skip, e.category "
            "FROM vialon_mappings m "
            "LEFT JOIN equipment e ON e.id = m.equipment_id "
            "WHERE m.wialon_id IS NOT NULL").fetchall()
    except sqlite3.OperationalError:
        # Нет таблиц сопоставления вовсе (фикстура, пустая тестовая база):
        # не исключается ничего, ровно как до появления этого модуля.
        return {}
    marked, kept, non_field, field = set(), set(), set(), set()
    for wialon_id, skip, category in rows:
        unit_id = int(wialon_id)
        (marked if skip else kept).add(unit_id)
        if category is None:
            continue
        (non_field if category in NON_FIELD_CATEGORIES else field).add(unit_id)
    not_ours = marked - kept
    out = {unit_id: EXCLUDED_NOT_OURS for unit_id in not_ours}
    for unit_id in (non_field - field) - not_ours:
        out[unit_id] = EXCLUDED_NON_FIELD
    return out
