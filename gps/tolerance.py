# -*- coding: utf-8 -*-
"""Светофор гектаров: допуски владельца и вердикт. Только stdlib.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ
Допуски нужны двум сверкам: «Сверке нарядов» (`gps_routes.py`, служба Flask)
и сверке заявок agro-work (`agro_work/reconcile.py`, общей с отчётом
`tools/agro_work_reconcile.py`, который живёт на stdlib и openpyxl и Flask
не тянет). Правило одно -- ответ владельца на вопрос В-2. Две копии одного
правила расходятся молча: наряд был бы «в допуске», а заявка с тем же
расхождением -- «на грани».

Модуль ничего не читает и ничего не пишет: числа на входе, вердикт на
выходе.
"""

# [REASON]: допуски заданы владельцем (вопрос В-2, закрыт 2026-08-12) и здесь
# только записаны, не выведены. Абсолютная добавка обязательна и не является
# украшением: ручной ввод округляется сеткой 0,5 га, и на поле 2 га одно
# округление даёт ±12% — процентный допуск в одиночку залил бы очередь
# ложными «жёлтыми».
TOLERANCE_GA_OK = (0.10, 0.3)      # доля, абсолютная добавка в га
TOLERANCE_GA_WARN = (0.20, 0.5)

VERDICT_OK = 'ok'
VERDICT_WARN = 'warn'
VERDICT_FAIL = 'fail'


def verdict_for_ga(base, fact):
    """Светофор по гектарам. Возвращает (вердикт, расхождение, доля).

    Сравнивается с тем объёмом, который закрыл человек, а не с планом, если
    закрытый есть: сверяется факт против того, за что выставят счёт.
    """
    deviation = fact - base
    # [REASON]: округление ДО сравнения, иначе граница решается ошибкой
    # представления. 2,0 - 1,7 в двоичной плавающей точке даёт
    # 0.30000000000000004, и расхождение ровно в допуск (0,3 га) уезжало в
    # «жёлтое». Шесть знаков -- это 0,01 квадратного метра, на четыре порядка
    # мельче любого реального разрешения метода, и граница ведёт себя так, как
    # написано в допуске: «не больше» значит не больше.
    size = round(abs(deviation), 6)
    share = (deviation / base) if base else None
    if size <= round(max(TOLERANCE_GA_OK[0] * abs(base), TOLERANCE_GA_OK[1]), 6):
        return VERDICT_OK, deviation, share
    if size <= round(max(TOLERANCE_GA_WARN[0] * abs(base), TOLERANCE_GA_WARN[1]), 6):
        return VERDICT_WARN, deviation, share
    return VERDICT_FAIL, deviation, share


# [REASON]: допуск моточасов -- тот же ответ владельца на вопрос В-2
# (12.08): в допуске -- расхождение не больше max(15 %, 0,5 ч), на грани --
# не больше 25 %, дальше -- вне допуска. Нужен сверке заявок метода «время»
# (agro-work, решение владельца 09.10: моточас -- время с включённым
# зажиганием по трекеру).
TOLERANCE_HOURS_OK = (0.15, 0.5)   # доля, абсолютная добавка в часах
TOLERANCE_HOURS_WARN = 0.25        # доля, без абсолютной добавки


def verdict_for_hours(base, fact):
    """Светофор по часам. Возвращает (вердикт, расхождение, доля).

    Округление до сравнения -- по той же причине, что у гектаров: граница
    «не больше» не должна решаться ошибкой представления.
    """
    deviation = fact - base
    size = round(abs(deviation), 6)
    share = (deviation / base) if base else None
    if size <= round(max(TOLERANCE_HOURS_OK[0] * abs(base),
                         TOLERANCE_HOURS_OK[1]), 6):
        return VERDICT_OK, deviation, share
    if size <= round(TOLERANCE_HOURS_WARN * abs(base), 6):
        return VERDICT_WARN, deviation, share
    return VERDICT_FAIL, deviation, share
