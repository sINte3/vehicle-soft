# -*- coding: utf-8 -*-
"""drone_collector/browser.py -- drive SmartFarm in a real browser and capture
the flight-list responses it fetches for itself.

Why a browser at all. DJI signs every API request with a `Signature` header
generated by its own bundled WASM. Tested against the live site on 2026-07-31:
dropping the header returns body `code 101`, and rewriting `page_size=30` to
`page_size=100` on an otherwise genuine request also returns `code 101`. So the
requests are issued by the site, and we only listen. Three consequences run
through this whole module:

  * nothing in a URL may be edited after the site has signed it;
  * the reporting period cannot be put into the URL -- it is set through the
    site's own date picker and then VERIFIED against the URL the site produced;
  * pagination is by page number, through the site's own control.

Note what the signature test does NOT prove. It proves that an ALTERED URL is
rejected, not that the values in it are fixed. page_size in particular is a
per-session setting with its own control on the page: when that control is
used, the app signs a request carrying the new value. It has been observed at
30 in one session and 50 in another. maximise_page_size() therefore drives
that control -- and only that control.

Do not try to generate, replay or reverse-engineer the Signature header. It
has been tested and it does not work.

serial_number is NOT a machine identifier. It is unique per flight (verified
on 10 385 records), so it is a second flight id. Nothing here keys, groups or
deduplicates on it; deduplication is on `id` alone.

Success is NOT the HTTP status. Every response is HTTP 200; success or failure
is the `code` field inside the JSON body: 200 means data, 101 and 408 mean
rejection. Any code path that decides success from response.status is wrong.

Selectors. The site cannot be reached from the development machine, so every
selector below is a module-level constant with a comment: when one turns out
to be wrong on the live cabinet it is corrected here, in one place, and
nowhere else.
"""

import logging
import re
import time

from datetime import datetime, timedelta

from urllib.parse import parse_qs, urlsplit

log = logging.getLogger(__name__)


# ─── The API we listen to ─────────────────────────────────────────────────────

# The flight LIST call. The trailing '?' is part of the marker: it is what
# separates the list endpoint from a flight detail URL.
FLIGHT_LIST_URL_MARKER = '/api/web/v1/flight_records?'

# [REASON]: matching is done on the endpoint name, not on the API version, so
# that a version bump on DJI's side does not turn every run into a silent
# "0 flights collected". A URL that matches this but not the full marker above
# is captured AND logged as an API-version change, so the constant can be
# corrected deliberately instead of being discovered by an empty database.
# It is still specific: the same page also fetches /aggr? and /aggr_by_day?
# with the very same filter parameters, and neither matches this.
FLIGHT_LIST_URL_MARKER_LOOSE = '/flight_records?'

# Detail URLs look like /api/web/v1/flight_records/574320663 and must never be
# captured -- their body has no `data` list and no meta_data.
FLIGHT_DETAIL_URL_MARKER = '/flight_records/'

# In-body status. NOT the HTTP status: every response is HTTP 200.
BODY_CODE_OK = 200

# Query parameters carrying the period, as the site itself spells them. They
# arrive percent-encoded (filters%5Btimestamp_gteq%5D); parse_qs decodes both
# keys and values, so the decoded spelling is what we match on.
PARAM_PERIOD_FROM = 'filters[timestamp_gteq]'
PARAM_PERIOD_TO = 'filters[timestamp_lteq]'


