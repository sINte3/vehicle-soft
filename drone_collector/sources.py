def utc_stamp(now=None):
    """`YYYY-MM-DD HH:MM:SS` in UTC -- the receiver's `captured_at_utc`."""
    moment = now or datetime.now(timezone.utc)
    return moment.strftime('%Y-%m-%d %H:%M:%S')


def capture_run_id(date_from=None, date_to=None, now=None):
    """`sources:<from>_<to>:<UTC stamp>`. Carries no secret."""
    moment = now or datetime.now(timezone.utc)
    stamp = moment.strftime('%Y%m%dT%H%M%SZ')
    if date_from and date_to:
        span = '%s_%s' % (date_from, date_to)
    else:
        span = 'ids-file'
    return 'sources:%s:%s' % (span, stamp)


def url_path(url):
    """The path of a URL, without scheme, host, query or fragment."""
    try:
        return urlsplit(str(url)).path or ''
    except ValueError:
        return ''


def host_and_path(url):
    """`host/path` of a URL with the query string and fragment removed.

    [REASON]: the query of a storage link IS the credential
    (`Expires`, `OSSAccessKeyId`, `Signature`). The host and the path say
    which object was named; nothing else survives.
    """
    try:
        parts = urlsplit(str(url))
    except ValueError:
        return None
    if not parts.netloc and not parts.path:
        return None
    return parts.netloc + parts.path


def api_version_of(path):
    match = _API_VERSION.search(path or '')
    if match:
        return match.group(1)
    if V4_PATH.search(path or ''):
        return API_VERSION_STORAGE
    return None


def classify_source_url(url, method='GET'):
    """(source_type, flight id named in the path) -- or (None, None)."""
    path = url_path(url)
    verb = (method or 'GET').upper()
    match = CARD_PATH.match(path)
    if match and verb == 'GET':
        return SOURCE_CARD, int(match.group(1))
    match = AIRLINES_PATH.match(path)
    if match and verb == 'GET':
        return SOURCE_AIRLINES, int(match.group(1))
    if verb == 'POST' and path.rstrip('/') == ROUTE_PATH:
        return SOURCE_ROUTE, None
    match = V4_PATH.search(path)
    if match and verb == 'GET':
        return SOURCE_V4, int(match.group(1))
    return None, None


def body_code(body):
    """In-body `code` of a JSON envelope, or None when there is none."""
    try:
        document = json.loads(bytes(body).decode('utf-8'))
    except (ValueError, UnicodeDecodeError, TypeError):
        return None
    if not isinstance(document, dict):
        return None
    code = document.get('code')
    if isinstance(code, bool) or not isinstance(code, int):
        return None
    return code


def airlines_document(body):
    """The derived airlines record, or None when the body is not its JSON.

    Keys: `code`, `status`, and `<link>_path` for `file_v4_url`,
    `std_detail_url`, `std_summary_url` -- host+path without the query, or
    None when DJI sent no link. This is the ONLY form in which the airlines
    answer is ever kept.
    """
    try:
        document = json.loads(bytes(body).decode('utf-8'))
    except (ValueError, UnicodeDecodeError, TypeError):
        return None
    if not isinstance(document, dict):
        return None
    data = document.get('data')
    airline = data.get('airline') if isinstance(data, dict) else None
    airline = airline if isinstance(airline, dict) else {}
    out = {'code': document.get('code'), 'status': document.get('status')}
    for key in ('file_v4_url', 'std_detail_url', 'std_summary_url'):
        value = airline.get(key)
        out[key + '_path'] = (host_and_path(value)
                              if isinstance(value, str) and value else None)
    return out


def airlines_bytes(document):
    """Canonical bytes of the derived record -- what is hashed and stored."""
    return json.dumps(document, ensure_ascii=False, sort_keys=True,
                      separators=(',', ':')).encode('utf-8')


def v4_url_present(document):
    return bool(document and document.get('file_v4_url_path'))


def body_secret_markers(body):
    """Markers of a signed link or credential in a raw body. Empty -- clean.

    Runs the queue's detector AND the receiver's list over the body decoded
    as text, so a body the receiver would refuse is refused here first.
    """
    text = bytes(body).decode('utf-8', errors='ignore')
    found = set(find_secret_markers(text))
    lowered = text.lower()
    for marker in RECEIVER_SECRET_MARKERS:
        if marker in lowered:
            found.add(marker.rstrip('=:'))
    return sorted(found)


def route_identity(body, expected_flight_id):
    """(status, embedded flight ids) of a route body against the visited flight.

    [REASON]: the route POST names the flight in its BODY, not in its URL,
    so the only proof that a captured route belongs to the flight whose page
    asked for it is the flight id the protobuf itself carries. A mismatch is
    still stored -- the receiver quarantines it -- but it is counted, because
    a route filed under the wrong flight is exactly the kind of quiet wrong
    number this whole track exists to prevent.
    """
    from drone_collector.route_decode import (RouteDecodeError,
                                              decode_route_response)
    try:
        decoded = decode_route_response(bytes(body))
    except RouteDecodeError:
        return ROUTE_IDENTITY_UNDECODABLE, []
    ids = [value for value in decoded.flight_ids if value is not None]
    if not ids:
        # An empty or non-OK envelope names nobody: nothing to disagree with.
        return ROUTE_IDENTITY_OK, ids
    if expected_flight_id in ids and len(set(ids)) == 1:
        return ROUTE_IDENTITY_OK, ids
    return ROUTE_IDENTITY_MISMATCH, ids


def source_item(flight_id, source_type, body, captured_at, path,
                association, api_status, run_id, parser_version=None,
                schema_version=None, extra_context=None):
    """One item of the `sources` list of /drones/api/source_sync.

    `body` is the raw bytes; `sha256` and `size_bytes` are computed from
    exactly those bytes, and the receiver recomputes both.
    """
    raw = bytes(body)
    context = {'path': path, 'association': association,
               'api_version': api_version_of(path),
               'mode_version': SOURCES_MODE_VERSION}
    if extra_context:
        context.update(extra_context)
    return {
        'flight_id': int(flight_id),
        'source_type': source_type,
        'captured_at_utc': captured_at,
        'body_b64': base64.b64encode(raw).decode('ascii'),
        'sha256': hashlib.sha256(raw).hexdigest(),
        'size_bytes': len(raw),
        'request_context': context,
        'capture_run_id': run_id,
        'parser_version': parser_version,
        'schema_version': schema_version,
        'api_status': api_status,
    }


def source_identity(flight_id, source_type):
    return '%d:%s' % (int(flight_id), source_type)


