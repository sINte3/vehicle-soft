def source_items(flight, run_id, exclude=None):
    """The source_sync items of a flight, in a stable order."""
    skip = set(exclude or ())
    items = []
    for source_type in VISIT_SOURCE_TYPES:
        captured = flight.items.get(source_type)
        if captured is None or source_type in skip:
            continue
        parser_version = schema_version = None
        if source_type == SOURCE_CARD:
            schema_version = SCHEMA_RAW_HTTP_BODY
        elif source_type == SOURCE_AIRLINES:
            schema_version = SCHEMA_AIRLINES_PATHS_ONLY
        elif source_type == SOURCE_ROUTE:
            parser_version = _decoder_version()
        elif source_type == SOURCE_V4:
            parser_version = V4_PARSER_VERSION
        extra = dict(captured.extra_context)
        if captured.http_status is not None:
            extra['http_status'] = captured.http_status
        extra['method'] = captured.method
        items.append(source_item(
            flight.flight_id, source_type, captured.body, captured.captured_at,
            captured.path, captured.association, captured.api_status, run_id,
            parser_version=parser_version, schema_version=schema_version,
            extra_context=extra))
    return items


def _decoder_version():
    from drone_collector.route_decode import DECODER_VERSION
    return DECODER_VERSION


class EnqueueResult(object):
    __slots__ = ('queued', 'duplicates', 'too_large', 'secret_refused')

    def __init__(self):
        self.queued = 0
        self.duplicates = 0
        self.too_large = 0
        self.secret_refused = 0

    def as_dict(self):
        return {'queued': self.queued, 'duplicates': self.duplicates,
                'too_large': self.too_large,
                'secret_refused': self.secret_refused}


def enqueue_sources(outbox, items, flight=None, diagnostics=None,
                    logger=None):
    """Queue source items. Returns an EnqueueResult.

    A body carrying a marker of a signed link is refused BEFORE the queue
    sees it and counted; one above the envelope cap is counted as well. Both
    are left out rather than poisoning a batch the receiver would refuse
    whole.
    """
    out = logger or log
    result = EnqueueResult()
    for item in items:
        raw = base64.b64decode(item['body_b64'])
        markers = body_secret_markers(raw)
        if markers:
            result.secret_refused += 1
            out.error('Flight %d %s: the body carries %s; NOT queued',
                      item['flight_id'], item['source_type'],
                      ', '.join(markers))
            continue
        extra = dict(diagnostics or {})
        extra['mode_version'] = SOURCES_MODE_VERSION
        if item['source_type'] == SOURCE_AIRLINES:
            # Read back by the resumable skip: "no V4 at DJI" is a complete
            # capture and must not be asked for again.
            extra['v4_url_present'] = bool(
                v4_url_present(json.loads(raw.decode('utf-8'))))
        identity = source_identity(item['flight_id'], item['source_type'])
        try:
            _path, duplicate = outbox.enqueue(
                KIND_SOURCE, identity, item, item['sha256'],
                source='dji-record-page', diagnostics=extra)
        except EnvelopeTooLarge:
            result.too_large += 1
            out.error('Flight %d %s: %d bytes exceed the envelope cap; NOT '
                      'queued', item['flight_id'], item['source_type'],
                      item['size_bytes'])
            continue
        except SecretInEnvelope as exc:
            result.secret_refused += 1
            out.error('Flight %d %s: %s', item['flight_id'],
                      item['source_type'], exc)
            continue
        if duplicate:
            result.duplicates += 1
        else:
            result.queued += 1
        if flight is not None:
            flight.enqueued.add(item['source_type'])
    return result


# ─── Resumable skip ──────────────────────────────────────────────────────────

_KNOWN_NAME = re.compile(r'^source_(\d+)_(%s)_[0-9a-f]{16}\.json$'
                         % '|'.join(SOURCE_TYPES))


def known_sources(outbox):
    """{flight_id: {source_type: path}} from the file names of the queue.

    [REASON]: built from NAMES, not from reading every envelope. A month of
    flights is thirty thousand envelopes, and a V4 envelope is a megabyte;
    reading them to learn what is already there would take longer than the
    visits it saves.
    """
    known = {}
    try:
        paths = outbox.records(KIND_SOURCE)
    except OutboxError:
        return known
    for path in paths:
        match = _KNOWN_NAME.match(Path(path).name)
        if not match:
            continue
        known.setdefault(int(match.group(1)), {})[match.group(2)] = path
    return known


def flight_already_captured(flight_id, known, outbox):
    """True when the queue already holds everything a visit could bring."""
    types = known.get(int(flight_id)) or {}
    if not all(source_type in types
               for source_type in (SOURCE_CARD, SOURCE_ROUTE,
                                   SOURCE_AIRLINES)):
        return False
    if SOURCE_V4 in types:
        return True
    try:
        envelope = outbox.read(types[SOURCE_AIRLINES])
    except OutboxError:
        return False
    diagnostics = envelope.get('diagnostics') or {}
    return diagnostics.get('v4_url_present') is False


# ─── Dry run ─────────────────────────────────────────────────────────────────

def sources_dry_run_path(out_dir, run_id):
    safe = re.sub(r'[^A-Za-z0-9._-]+', '_', run_id)
    return Path(out_dir) / ('sources_dry_run_%s.json' % safe)


def write_sources_dry_run(items, flights, out_dir, run_id):
    """What would have been queued. Nothing is queued.

    [REASON]: the text is checked for secret markers BEFORE it is written --
    the same check the queue makes -- because a dry run is the one path by
    which a body reaches the disk without passing through the queue.
    """
    # [REASON]: the DECODED body is checked too, exactly as `enqueue_sources`
    # does before queueing. `find_secret_markers` reads the report as text,
    # and a signed link inside `body_b64` is invisible to it -- so without
    # this the dry run writes to disk precisely what a real run refuses to
    # hold, and the dry run is the path an operator reaches for when
    # something already looks wrong.
    for item in items:
        markers = body_secret_markers(base64.b64decode(item['body_b64']))
        if markers:
            raise SecretInEnvelope(
                'flight %s %s carries %s; nothing was written'
                % (item.get('flight_id'), item.get('source_type'),
                   ', '.join(markers)))
    target = sources_dry_run_path(out_dir, run_id)
    document = {
        'dry_run': True,
        'nothing_was_queued': True,
        'capture_run_id': run_id,
        'count': len(items),
        'flights': [flight.describe() for flight in flights],
        'sources': items,
    }
    text = json.dumps(document, ensure_ascii=False, indent=1)
    found = find_secret_markers(text)
    if found:
        raise SecretInEnvelope('the dry-run report carries %s; nothing was '
                               'written' % ', '.join(found))
    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open('w', encoding='utf-8') as handle:
        handle.write(text)
    return target


# ─── Sending the queue ───────────────────────────────────────────────────────

class SourceDrainResult(object):
    """What became of the source queue in one sending run."""

    __slots__ = ('envelopes', 'sent', 'left_pending', 'corrupt', 'batches',
                 'counters', 'accepted', 'refusal_reasons')

    def __init__(self):
        self.envelopes = 0
        self.sent = 0
        self.left_pending = 0
        self.corrupt = 0
        self.batches = 0
        self.counters = None
        self.accepted = True
        self.refusal_reasons = []

    def as_dict(self):
        base = {'envelopes': self.envelopes, 'sent': self.sent,
                'left_pending': self.left_pending, 'corrupt': self.corrupt,
                'batches': self.batches, 'accepted': self.accepted}
        if self.counters is not None:
            base.update(self.counters.as_dict())
        return base


def source_refusal_reasons(counters, expected):
    """Why a source batch was NOT accepted in full. Empty -- accepted.

    Full acceptance is four conditions at once, none implied by HTTP 200:
    `status == "ok"`, `seen == len(batch)`, `errors == 0` and counters that
    add up. On any other answer the batch stays in `pending/` whole: the
    receiver answers with counters, not with a list, so which items landed
    cannot be known -- and re-sending is safe because a body already stored
    comes back as a duplicate, not as a second revision.
    """
    if counters is None:
        return ['the endpoint returned no counters at all']
    reasons = []
    if counters.status != 'ok':
        reasons.append('the endpoint answered status %r' % (counters.status,))
    if not counters.counters_agree:
        reasons.append('the counters do not add up: seen=%d but '
                       'new+duplicates+errors=%d'
                       % (counters.seen, counters.new + counters.duplicates
                          + counters.errors))
    if counters.errors:
        reasons.append('%d source(s) were rejected by the endpoint'
                       % counters.errors)
    if counters.seen != expected:
        reasons.append('the endpoint saw %d source(s) of the %d that were '
                       'sent' % (counters.seen, expected))
    return reasons


def _readable_pending(outbox, prefix, logger, result):
    from drone_collector.outbox import CorruptEnvelope
    readable = []
    for path in outbox.pending():
        if not path.name.startswith(prefix):
            continue
        try:
            envelope = outbox.read(path)
        except CorruptEnvelope as exc:
            outbox.quarantine(path)
            result.corrupt += 1
            logger.error('Queue entry %s is unreadable (%s); moved to '
                         'corrupt/ and left out of this run.', path.name, exc)
            continue
        readable.append((path, envelope))
    return readable


def drain_source_outbox(outbox, cfg, logger, send_fn=None):
    """POST pending source envelopes in chunks; move the accepted to `sent/`.

    Each chunk is judged on its own: an accepted chunk moves, a refused one
    stops the run and leaves itself and everything after it in `pending/`.
    Network and server errors propagate as the sender raises them, with
    nothing moved.

    [REASON]: `mark_sent` is called ONLY after the receiver accepted the
    chunk in full, and never before -- the opposite order loses bodies in
    exactly the case the on-disk queue exists for.
    """
    from drone_collector.sender import chunk_sources, send_sources

    send = send_fn or send_sources
    result = SourceDrainResult()
    readable = _readable_pending(outbox, KIND_SOURCE + '_', logger, result)
    result.envelopes = len(readable)
    if not readable:
        logger.info('The source queue holds nothing to send.')
        result.left_pending = len(outbox.pending())
        return result

    from drone_collector.sender import SourceSendResult
    total = SourceSendResult()
    chunks = chunk_sources(readable, getattr(cfg, 'source_batch_size', None))
    for index, chunk in enumerate(chunks, start=1):
        bodies = [envelope['body'] for _path, envelope in chunk]
        counters = send(bodies, cfg, logger=logger)
        result.batches += 1
        if counters is not None:
            total.add(counters.as_dict())
            total.status = counters.status
        refusals = source_refusal_reasons(counters, len(bodies))
        if refusals:
            result.accepted = False
            result.refusal_reasons = refusals
            for reason in refusals:
                logger.error('Source chunk %d/%d was NOT fully accepted: %s',
                             index, len(chunks), reason)
            logger.error('%d envelope(s) of this chunk and %d after it stay '
                         'in pending/; nothing was lost.', len(chunk),
                         sum(len(rest) for rest in chunks[index:]))
            break
        for path, _envelope in chunk:
            outbox.mark_sent(path)
            result.sent += 1
    result.counters = total
    result.left_pending = len(outbox.pending())
    return result


