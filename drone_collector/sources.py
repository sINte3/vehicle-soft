# -*- coding: utf-8 -*-
"""drone_collector/sources.py -- the immutable DJI source bodies of a flight.

    python -m drone_collector.main --sources --from 2026-08-01 --to 2026-08-31
    python -m drone_collector.main --sources --ids-file ids.txt --dry-run
    python -m drone_collector.main --sources --ids-file ids.txt --send-sources
    python -m drone_collector.main --land-snapshot [--with-geometry] [--send-snapshot]

DJI-AREA-EVIDENCE-001. Vehicle Soft keeps, per flight, the BYTES DJI served
-- not a reading of them -- so that every later figure can be re-derived
from the source instead of being believed. This module captures those bytes
and queues them for `POST /drones/api/source_sync`; a second mode snapshots
the Field Management catalog for `POST /drones/api/land_snapshot_sync`.

WHAT ONE FLIGHT VISIT CAPTURES

The collector navigates the SmartFarm SPA to `/record/<flight_id>` and
LISTENS. While the page loads, the SPA itself issues, in this order:

  card      GET  .../api/web/v1/flight_records/<id>          JSON envelope
  route     POST .../api/web/v2/flight_datas/flight_records  protobuf
  airlines  GET  .../api/web/v2/airlines/<id>                JSON with
                                                             SIGNED links
  v4        GET  .../objects/airline_v4/<id>/...?Expires=..&Signature=..
                                                             protobuf, up to
                                                             a megabyte

The airlines path has NO `flight_datas/` segment, unlike the route beside
it. That is DJI's spelling, not a typo of ours: `services/protoRequest.ts`
of the SPA reads `mixApi(`/api/web/v2/airlines/${id}`)`, and a captured
record-page trace shows the same. Assuming the symmetry cost a whole run --
see the [REASON] on `AIRLINES_PATH`.

The card, the route and the V4 file are stored byte for byte. The airlines
descriptor is NOT: its whole payload is three pre-signed storage links, each
a temporary credential. Only a derived document survives -- the envelope
code and status plus host+path of every link with the query string removed
-- and it is the ABSENCE of `file_v4_url` in it that records "DJI holds no
V4 for this flight" (`NO_V4_URL`), which is a finding in its own right.

WHY THE V4 BODY GOES THROUGH `page.route`, AND WHY THAT IS STILL LISTENING

[REASON]: the V4 body is read inside a `page.route` handler --
`resp = route.fetch(); body = resp.body(); route.fulfill(response=resp,
body=body)` -- and not from the `response` / `requestfinished` events like
the three small bodies. On the August 2026 forensic run, reading bodies of
that size from the events lost about one in four under load: Chromium had
already evicted the body when Playwright asked for it
(`Network.getResponseBody: No resource with given identifier`). With
`page.route` Playwright owns the bytes from the first one.

This does NOT breach the rule that the collector only listens. The request
is still the SPA's own: the page built it, the page's WASM signed it, and
`route.fetch()` continues THAT request with its URL, headers and signature
untouched. Nothing is altered, nothing is replayed, nothing is generated by
us, and the page receives exactly the response the storage sent. The
difference from the event path is who holds the buffer, not who asked.

WHAT NEVER ENTERS THE QUEUE

No signed link, no query string of a storage URL, no cookie, no header
value. `request_context.path` is the URL PATH -- for the V4 object,
`/api/web/v2/flight_datas/objects/airline_v4/<id>/<file>` -- with the query
cut off before the string is even built. Every body is checked for the
markers of a signed link before it is queued, and the queue checks the
serialised envelope once more.

RESUMABLE

A flight whose card, route and airlines are already in the outbox (pending
or sent), together with either its V4 or an airlines record that says there
is none, is not visited again. A re-run therefore asks DJI only for what is
still missing -- the same rule the polygon run has.
"""

