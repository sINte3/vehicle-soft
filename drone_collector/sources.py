class CapturedSource(object):
    """One body of one flight, as it came off the wire."""

    __slots__ = ('source_type', 'body', 'path', 'http_status', 'api_status',
                 'captured_at', 'method', 'association', 'extra_context')

    def __init__(self, source_type, body, path, http_status=None,
                 api_status=None, captured_at=None, method='GET',
                 association='url_path', extra_context=None):
        self.source_type = source_type
        self.body = bytes(body)
        self.path = path
        self.http_status = http_status
        self.api_status = api_status
        self.captured_at = captured_at or utc_stamp()
        self.method = method
        self.association = association
        self.extra_context = extra_context or {}

    def __repr__(self):
        return '<CapturedSource %s %d bytes>' % (self.source_type,
                                                 len(self.body or b''))


class FlightSources(object):
    """Everything one record-page visit yielded for one flight."""

    __slots__ = ('flight_id', 'items', 'status', 'v4_url_present',
                 'v4_failed', 'route_identity', 'route_embedded_ids',
                 'error_type', 'rejected', 'enqueued')

    def __init__(self, flight_id):
        self.flight_id = int(flight_id)
        self.items = {}
        self.status = None
        self.v4_url_present = None
        self.v4_failed = False
        self.route_identity = None
        self.route_embedded_ids = []
        self.error_type = None
        self.rejected = {}
        self.enqueued = set()

    def has(self, source_type):
        return source_type in self.items

    @property
    def v4_decided(self):
        """The V4 question has an answer: captured, absent at DJI, or failed."""
        return (self.has(SOURCE_V4) or self.v4_url_present is False
                or self.v4_failed)

    @property
    def settled(self):
        """Nothing more is expected from this page: stop waiting."""
        return (self.v4_decided and self.has(SOURCE_CARD)
                and self.has(SOURCE_ROUTE) and self.has(SOURCE_AIRLINES))

    @property
    def complete(self):
        """Card, route, airlines and either the V4 or DJI's word that there
        is none. `NO_V4_URL` is a complete capture; a timeout is not."""
        return (self.has(SOURCE_CARD) and self.has(SOURCE_ROUTE)
                and self.has(SOURCE_AIRLINES)
                and (self.has(SOURCE_V4) or self.v4_url_present is False))

    def outcome(self):
        if self.status == STATUS_PAGE_ERROR:
            return STATUS_PAGE_ERROR
        if self.has(SOURCE_V4):
            return STATUS_V4
        if self.v4_url_present is False:
            return STATUS_NO_V4_URL
        if self.v4_failed:
            return STATUS_V4_FAILED
        return STATUS_NO_V4

    def note_rejected(self, reason):
        self.rejected[reason] = self.rejected.get(reason, 0) + 1

    def release(self):
        """Drop the bodies once they are queued; keep the flags."""
        for item in self.items.values():
            item.body = b''

    def describe(self):
        return {'flight_id': self.flight_id, 'status': self.status,
                'sources': sorted(self.items),
                'v4_url_present': self.v4_url_present,
                'route_identity': self.route_identity,
                'rejected': dict(self.rejected),
                'error_type': self.error_type}


class SourceCapture(object):
    """The listener. Attach it to the page, then visit flights.

    Listeners never raise: an exception inside a Playwright handler surfaces
    in its event loop and aborts the navigation. Everything is counted.
    """

    def __init__(self, logger=None, max_body_bytes=MAX_SOURCE_BODY_BYTES,
                 clock=None):
        self.log = logger or log
        self.max_body_bytes = max_body_bytes
        self.clock = clock or utc_stamp
        self.flights = {}
        self.current_flight_id = None
        self.listener_errors = 0
        self.oversized = 0
        self.unattributed = 0
        self.v4_handler_errors = 0
        self.requests_failed = 0
        self.airlines_unmatched = 0
        self.airlines_unmatched_paths = []
        self.rejected = {}

    # -- lifecycle ------------------------------------------------------------

    def attach(self, page):
        """Subscribe to the page. The V4 route is registered here too."""
        page.on('requestfinished', self.note_request_finished)
        page.on('requestfailed', self.note_request_failed)
        page.route(V4_URL_PATTERN, self.handle_v4)

    def begin_flight(self, flight_id):
        flight = self.flights.get(int(flight_id))
        if flight is None:
            flight = FlightSources(flight_id)
            self.flights[flight.flight_id] = flight
        self.current_flight_id = flight.flight_id
        return flight

    def flight(self, flight_id):
        flight = self.flights.get(int(flight_id))
        if flight is None:
            flight = FlightSources(flight_id)
            self.flights[flight.flight_id] = flight
        return flight

    # -- the small bodies: card, route, airlines --------------------------------

    def note_request_finished(self, request):
        try:
            self._on_request_finished(request)
        except Exception as exc:
            self.listener_errors += 1
            self.log.warning('Source listener failed (%s); %d such failure(s)'
                             ' so far', safe_exception_name(exc),
                             self.listener_errors)

    def note_request_failed(self, request):
        try:
            source_type, _fid = classify_source_url(
                getattr(request, 'url', ''), getattr(request, 'method', 'GET'))
        except Exception:
            source_type = None
        if source_type is not None:
            self.requests_failed += 1
            self.log.warning('A %s request of the page failed before its '
                             'body arrived', source_type)

    def _on_request_finished(self, request):
        url = getattr(request, 'url', '') or ''
        method = getattr(request, 'method', 'GET') or 'GET'
        source_type, path_flight_id = classify_source_url(url, method)
        if source_type is None:
            self._note_airlines_lookalike(url_path(url))
            return
        if source_type == SOURCE_V4:
            # V4 is owned by the route handler; the event path must not
            # read the same body a second time.
            return
        response = request.response()
        if response is None:
            self._note_rejected(source_type, 'no-response')
            return
        status = getattr(response, 'status', None)
        body = response.body()
        path = url_path(url)
        self._accept(source_type, path_flight_id, body, path, status,
                     method, request)

    def _accept(self, source_type, path_flight_id, body, path, status,
                method, request=None):
        if body is None:
            self._note_rejected(source_type, 'no-body')
            return
        if len(body) > self.max_body_bytes:
            self.oversized += 1
            self._note_rejected(source_type, 'oversized')
            return

        if source_type == SOURCE_CARD:
            self._accept_card(path_flight_id, body, path, status, method)
        elif source_type == SOURCE_AIRLINES:
            self._accept_airlines(path_flight_id, body, path, status, method)
        elif source_type == SOURCE_ROUTE:
            self._accept_route(body, path, status, method, request)

    def _accept_card(self, flight_id, body, path, status, method):
        if flight_id is None:
            self.unattributed += 1
            return
        code = body_code(body)
        if status is not None and not 200 <= int(status) < 300:
            self.flight(flight_id).note_rejected('http-%s' % status)
            self._note_rejected(SOURCE_CARD, 'http-%s' % status)
            return
        if code != BODY_CODE_OK:
            # [REASON]: the decision is made on the in-body code, never on
            # the HTTP status: the API answers 200 for rejections too. A
            # `code 101` body is not the flight's card and must not become
            # a revision of it.
            self.flight(flight_id).note_rejected('code-%s' % code)
            self._note_rejected(SOURCE_CARD, 'code-%s' % code)
            return
        self._store(flight_id, CapturedSource(
            SOURCE_CARD, body, path, http_status=status, api_status=code,
            captured_at=self.clock(), method=method))

    def _accept_airlines(self, flight_id, body, path, status, method):
        if flight_id is None:
            self.unattributed += 1
            return
        # [REASON]: the same two guards the card has, and for a harder
        # reason. A refusal or a 5xx from this endpoint still answers with
        # JSON, and that JSON has no `airline.file_v4_url` -- so without the
        # guards the derived record says `file_v4_url_path: null`, which the
        # whole chain reads as DJI'S OWN WORD that no V4 exists. The visit
        # then counts as complete, the envelope carries
        # `v4_url_present=False`, and `flight_already_captured` retires the
        # flight for good: a transient error would be frozen into the
        # evidence as a finding, and no re-run could ever undo it. An error
        # body is not a descriptor and is not kept.
        code = body_code(body)
        if status is not None and not 200 <= int(status) < 300:
            self.flight(flight_id).note_rejected('http-%s' % status)
            self._note_rejected(SOURCE_AIRLINES, 'http-%s' % status)
            return
        if code != BODY_CODE_OK:
            self.flight(flight_id).note_rejected('code-%s' % code)
            self._note_rejected(SOURCE_AIRLINES, 'code-%s' % code)
            return
        document = airlines_document(body)
        if document is None:
            # The raw airlines body carries the signed links and is never
            # stored; without a readable document there is nothing to keep.
            self.flight(flight_id).note_rejected('airlines-unreadable')
            self._note_rejected(SOURCE_AIRLINES, 'unreadable')
            return
        flight = self.flight(flight_id)
        flight.v4_url_present = v4_url_present(document)
        self._store(flight_id, CapturedSource(
            SOURCE_AIRLINES, airlines_bytes(document), path,
            http_status=status,
            api_status=document.get('code')
            if isinstance(document.get('code'), int)
            and not isinstance(document.get('code'), bool) else None,
            captured_at=self.clock(), method=method,
            extra_context={'urls': 'stripped-to-host-and-path'}))

    def _accept_route(self, body, path, status, method, request):
        flight_id = self._route_flight_id(request)
        if flight_id is None:
            self.unattributed += 1
            self._note_rejected(SOURCE_ROUTE, 'unattributed')
            return
        flight = self.flight(flight_id)
        identity, embedded = route_identity(body, flight_id)
        flight.route_identity = identity
        flight.route_embedded_ids = embedded
        if identity == ROUTE_IDENTITY_MISMATCH:
            self.log.warning('Flight %d: the route body names another flight;'
                             ' stored for quarantine', flight_id)
        self._store(flight_id, CapturedSource(
            SOURCE_ROUTE, body, path, http_status=status, api_status=None,
            captured_at=self.clock(), method=method, association='page_visit',
            extra_context={'visited_flight_id': flight_id,
                           'route_identity': identity}))

    def _route_flight_id(self, request):
        """The flight the route POST asked for: its body names exactly one."""
        post_data = getattr(request, 'post_data', None) if request else None
        requested = read_request_ids(post_data)
        if requested.parsed and len(requested.ids) == 1:
            return next(iter(requested.ids))
        return self.current_flight_id

    # -- the V4 body: page.route ----------------------------------------------

    def handle_v4(self, route):
        """Continue the page's own signed request and keep the bytes.

        [REASON]: see the module docstring. `route.fetch()` performs THE
        request the page issued -- same URL, same headers, same signature;
        `route.fulfill(response=resp, body=body)` hands the page exactly what
        the storage sent. Nothing is edited on either leg.
        """
        request = getattr(route, 'request', None)
        url = getattr(request, 'url', '') or ''
        path = url_path(url)
        match = V4_PATH.search(path)
        flight_id = int(match.group(1)) if match else None
        try:
            response = route.fetch()
            body = response.body()
            status = getattr(response, 'status', None)
        except Exception as exc:
            self.v4_handler_errors += 1
            self.log.warning('The V4 fetch of flight %s failed (%s); the '
                             'request is continued without capture',
                             flight_id, safe_exception_name(exc))
            if flight_id is not None:
                self.flight(flight_id).v4_failed = True
            self._continue_quietly(route)
            return
        try:
            route.fulfill(response=response, body=body)
        except Exception as exc:
            # The page did not get its answer; the bytes are still ours.
            self.v4_handler_errors += 1
            self.log.warning('The V4 response of flight %s could not be '
                             'handed to the page (%s)', flight_id,
                             safe_exception_name(exc))
        try:
            self._accept_v4(flight_id, body, path, status)
        except Exception as exc:
            self.listener_errors += 1
            self.log.warning('The V4 body of flight %s was fetched but not '
                             'kept (%s)', flight_id, safe_exception_name(exc))

    def _continue_quietly(self, route):
        try:
            route.continue_()
        except Exception:
            pass

    def _accept_v4(self, flight_id, body, path, status):
        if flight_id is None:
            self.unattributed += 1
            self._note_rejected(SOURCE_V4, 'unattributed')
            return
        flight = self.flight(flight_id)
        if status is not None and not 200 <= int(status) < 300:
            # 403 here is almost always an expired signature.
            flight.v4_failed = True
            flight.note_rejected('http-%s' % status)
            self._note_rejected(SOURCE_V4, 'http-%s' % status)
            return
        if not body:
            flight.v4_failed = True
            self._note_rejected(SOURCE_V4, 'empty')
            return
        if len(body) > self.max_body_bytes:
            self.oversized += 1
            flight.v4_failed = True
            self._note_rejected(SOURCE_V4, 'oversized')
            return
        self._store(flight_id, CapturedSource(
            SOURCE_V4, body, path, http_status=status, api_status=None,
            captured_at=self.clock(), method='GET'))

    # -- bookkeeping ----------------------------------------------------------

    def _store(self, flight_id, item):
        flight = self.flight(flight_id)
        if item.source_type in flight.items:
            # The page fetched the same thing twice; the first answer stands.
            return
        flight.items[item.source_type] = item
        self.log.info('Flight %d: captured %s (%d bytes)', flight.flight_id,
                      item.source_type, len(item.body))

    def _note_rejected(self, source_type, reason):
        key = '%s:%s' % (source_type, reason)
        self.rejected[key] = self.rejected.get(key, 0) + 1

    def _note_airlines_lookalike(self, path):
        """An airlines-shaped path the classifier did not take. Diagnostics.

        [REASON]: see AIRLINES_LIKE_PATH. This counts, it never captures --
        a path that reaches here is by definition NOT a source, and the only
        thing it changes is that the summary can say what was seen instead
        of leaving `sources_airlines=0` to mean two different things. The
        path carries no query by construction (`url_path` cut it off), so
        naming it in the log cannot print a credential.

        [REASON]: the flight id is folded to `<id>` before the path is kept
        or said. A wrong path is wrong the same way on every flight, and
        without the folding the "distinct paths" list would grow one entry
        per flight and the warning would be repeated two hundred times --
        burying the run's own log under the very thing it is reporting.
        """
        if not path or not AIRLINES_LIKE_PATH.search(path):
            return
        self.airlines_unmatched += 1
        shape = _ID_SEGMENT.sub('<id>', path)
        if shape in self.airlines_unmatched_paths:
            return
        if len(self.airlines_unmatched_paths) >= MAX_AIRLINES_LOOKALIKES:
            return
        self.airlines_unmatched_paths.append(shape)
        self.log.warning('The page asked for %s, which names airlines but is'
                         ' not the airlines descriptor this collector knows'
                         ' (%s). No airlines record will be kept for these'
                         ' flights.', shape, AIRLINES_PATH.pattern)

    def counts(self):
        return {'listener_errors': self.listener_errors,
                'oversized': self.oversized,
                'unattributed': self.unattributed,
                'v4_handler_errors': self.v4_handler_errors,
                'requests_failed': self.requests_failed,
                'airlines_unmatched': self.airlines_unmatched,
                'airlines_unmatched_paths': list(
                    self.airlines_unmatched_paths),
                'rejected': dict(self.rejected)}


# ─── The visit ───────────────────────────────────────────────────────────────

class SourceRun(object):
    """Visit record pages one by one and wait for each to settle.

        run = SourceRun(page, capture, cfg, log)
        flight = run.capture_flight(673501214)

    `page` is the live Playwright page (or a fake in tests); the wait is
    pumped through `page.wait_for_timeout`, never `time.sleep`, so the
    listeners keep running while the page loads.
    """

    def __init__(self, page, capture, cfg, logger=None, clock=None,
                 poll_ms=SOURCE_POLL_MS):
        self.page = page
        self.capture = capture
        self.cfg = cfg
        self.log = logger or log
        self.clock = clock or monotonic_ms
        self.poll_ms = poll_ms
        self.consecutive_page_errors = 0

    def record_url(self, flight_id):
        return self.cfg.record_url_template.format(id=int(flight_id))

    def capture_flight(self, flight_id):
        from drone_collector.browser import SessionExpired

        flight = self.capture.begin_flight(flight_id)
        url = self.record_url(flight_id)
        try:
            self.page.goto(url, wait_until=NAVIGATION_WAIT_UNTIL,
                           timeout=self.cfg.page_timeout_ms)
        except Exception as exc:
            flight.status = STATUS_PAGE_ERROR
            flight.error_type = safe_exception_name(exc)
            self.consecutive_page_errors += 1
            self.log.error('Flight %d: the record page did not open (%s)',
                           flight.flight_id, flight.error_type)
            return flight

        landed = getattr(self.page, 'url', '') or ''
        if LOGIN_PATH in landed:
            raise SessionExpired(
                'the saved session is no longer signed in (landed on the '
                'login page while opening flight %d) -- run `python -m '
                'drone_collector.main --save-session` again'
                % flight.flight_id)

        self.consecutive_page_errors = 0
        settled = pump_until(self.page.wait_for_timeout, lambda: flight.settled,
                             self.clock, self.cfg.source_wait_ms, self.poll_ms)
        flight.status = flight.outcome()
        if not settled and flight.status == STATUS_NO_V4:
            self.log.warning('Flight %d: %d ms passed without a V4 body or a '
                             'word that there is none; captured so far: %s',
                             flight.flight_id, self.cfg.source_wait_ms,
                             ', '.join(sorted(flight.items)) or 'nothing')
        self.log.info('Flight %d: %s (%s)', flight.flight_id, flight.status,
                      ', '.join(sorted(flight.items)) or 'nothing captured')
        return flight

    @property
    def browser_looks_dead(self):
        return self.consecutive_page_errors >= MAX_CONSECUTIVE_PAGE_ERRORS

    def pause(self):
        if self.cfg.source_pause_ms:
            self.page.wait_for_timeout(self.cfg.source_pause_ms)


