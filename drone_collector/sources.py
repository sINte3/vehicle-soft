SNAPSHOT_MODE_VERSION = 'land-snapshot-1'

# [REASON]: the receiver caps a request at 1000 lands, and the queue caps an
# envelope at 8 MiB. A node is a kilobyte or two; a polygon in base64 is
# ten. A chunk is closed by whichever limit comes first, with room left for
# the envelope's own fields.
MAX_SNAPSHOT_CHUNK_BYTES = 6 * 1024 * 1024

SIGNED_URL_KEY = 'signedurl'


def snapshot_run_id(now=None):
    moment = now or datetime.now(timezone.utc)
    return 'lands:%s' % moment.strftime('%Y%m%dT%H%M%SZ')


def strip_signed_urls(value):
    """A deep copy with every `signedURL` key removed, at any depth.

    Case-insensitive on the key: the receiver strips the same name, and a
    DJI rename to `SignedUrl` must not slip a credential through.
    """
    if isinstance(value, dict):
        return {key: strip_signed_urls(item) for key, item in value.items()
                if not (isinstance(key, str) and key.lower() == SIGNED_URL_KEY)}
    if isinstance(value, list):
        return [strip_signed_urls(item) for item in value]
    return value


def snapshot_manifest_sha256(nodes):
    """sha256 over the sorted (uuid, contentMd5) pairs of the snapshot."""
    pairs = []
    for node in nodes:
        if not isinstance(node, dict):
            continue
        storage = ((node.get('geometry') or {}).get('storage')
                   if isinstance(node.get('geometry'), dict) else None)
        storage = storage if isinstance(storage, dict) else {}
        pairs.append([str(node.get('uuid')), storage.get('contentMd5')])
    pairs.sort(key=lambda pair: (pair[0], str(pair[1])))
    text = json.dumps(pairs, ensure_ascii=False, separators=(',', ':'))
    return hashlib.sha256(text.encode('utf-8')).hexdigest()


def _node_md5(node):
    storage = ((node.get('geometry') or {}).get('storage')
               if isinstance(node, dict) and isinstance(node.get('geometry'),
                                                        dict) else None)
    if not isinstance(storage, dict):
        return None
    value = storage.get('contentMd5')
    return str(value).lower() if value else None


def _json_size(value):
    return len(json.dumps(value, ensure_ascii=False,
                          separators=(',', ':')).encode('utf-8'))


def snapshot_chunk_bodies(run_id, captured_at, nodes, geometries=None,
                          expected_count=None, scope=None, complete=None,
                          max_nodes=None, max_bytes=MAX_SNAPSHOT_CHUNK_BYTES):
    """The request bodies of one snapshot, in order; the last is `final`.

    `geometries` is `{content_md5: body_b64}`; each polygon travels in the
    chunk of the first node that names its md5. Nodes must already be
    stripped of signed links.
    """
    from drone_collector.config import MAX_LAND_SNAPSHOT_BATCH_SIZE
    cap = min(int(max_nodes or MAX_LAND_SNAPSHOT_BATCH_SIZE),
              MAX_LAND_SNAPSHOT_BATCH_SIZE)
    if cap < 1:
        cap = 1
    geometries = dict(geometries or {})
    placed = set()

    chunks = []
    current, current_geoms, current_bytes = [], [], 0
    for node in nodes:
        md5 = _node_md5(node)
        geometry = None
        if md5 and md5 in geometries and md5 not in placed:
            geometry = {'content_md5': md5, 'body_b64': geometries[md5]}
        size = _json_size(node) + (_json_size(geometry) if geometry else 0)
        if current and (len(current) >= cap
                        or current_bytes + size > max_bytes):
            chunks.append((current, current_geoms))
            current, current_geoms, current_bytes = [], [], 0
        current.append(node)
        current_bytes += size
        if geometry:
            current_geoms.append(geometry)
            placed.add(md5)
    if current or not chunks:
        chunks.append((current, current_geoms))

    bodies = []
    total = len(chunks)
    for index, (chunk_nodes, chunk_geoms) in enumerate(chunks, start=1):
        final = index == total
        snapshot = {
            'capture_run_id': run_id,
            'captured_at_utc': captured_at,
            'expected_count': expected_count,
            'scope': dict(scope or {}),
            'chunk': index,
            'chunks': total,
            'final': final,
            'complete': (bool(complete) if complete is not None else None)
            if final else None,
            'manifest_sha256': snapshot_manifest_sha256(nodes)
            if final else None,
        }
        bodies.append({'snapshot': snapshot, 'lands': chunk_nodes,
                       'geometries': chunk_geoms})
    return bodies


def snapshot_body_sha256(body):
    text = json.dumps(body, ensure_ascii=False, sort_keys=True,
                      separators=(',', ':'))
    return hashlib.sha256(text.encode('utf-8')).hexdigest()


def snapshot_identity(run_id, index):
    return '%s:%04d' % (run_id, int(index))


def enqueue_snapshot_chunks(outbox, bodies, diagnostics=None, logger=None):
    """Queue the chunks of one snapshot. Returns an EnqueueResult."""
    out = logger or log
    result = EnqueueResult()
    for body in bodies:
        snapshot = body.get('snapshot') or {}
        identity = snapshot_identity(snapshot.get('capture_run_id'),
                                     snapshot.get('chunk') or 0)
        extra = dict(diagnostics or {})
        extra['mode_version'] = SNAPSHOT_MODE_VERSION
        extra['lands'] = len(body.get('lands') or [])
        extra['geometries'] = len(body.get('geometries') or [])
        try:
            _path, duplicate = outbox.enqueue(
                KIND_LAND_SNAPSHOT, identity, body, snapshot_body_sha256(body),
                source='dji-field-management', diagnostics=extra)
        except EnvelopeTooLarge:
            result.too_large += 1
            out.error('Snapshot chunk %s exceeds the envelope cap; NOT queued',
                      identity)
            continue
        except SecretInEnvelope as exc:
            result.secret_refused += 1
            out.error('Snapshot chunk %s: %s', identity, exc)
            continue
        if duplicate:
            result.duplicates += 1
        else:
            result.queued += 1
    return result


class GeometryDownloadCounters(object):
    __slots__ = ('selected', 'downloaded', 'no_geometry', 'failed',
                 'md5_mismatch', 'too_large', 'secret_in_payload', 'bytes',
                 # Уже лежит в неизменяемом хранилище приёмника -- пропущено
                 # ДО скачивания. Отдельно от `no_geometry` (у контура вообще
                 # нет полигона) и от внутрирунного дубля.
                 'known_skipped', 'duplicate_in_run')

    def __init__(self):
        for key in self.__slots__:
            setattr(self, key, 0)

    def as_dict(self):
        return {key: getattr(self, key) for key in self.__slots__}


def download_snapshot_geometries(nodes, download_fn, logger=None,
                                 sleep_fn=None, pause_s=0.35,
                                 max_bytes=MAX_SOURCE_BODY_BYTES,
                                 known_md5=None,
                                 progress_every=GEOMETRY_PROGRESS_EVERY):
    """{content_md5: body_b64} of the polygons of the given nodes.

    The bytes are kept VERBATIM -- the receiver stores them by md5 -- after
    the same three checks the polygon run makes: the download arrived, its
    md5 is the one DJI named, and it carries no signed link. The signed link
    is taken from the node once and cleared at once.

    `known_md5` is the set of `contentMd5` the receiver ALREADY stores. A
    contour whose md5 is in it is skipped BEFORE the download -- that is the
    whole point of the incremental run, and the test asserts it by checking
    that the link was never requested, not merely that the body was dropped.

    [REASON]: the md5 comes from the CATALOG node (`geometry.storage.
    contentMd5`), not from the downloaded bytes, so the decision is available
    before a single byte is fetched. Were it otherwise no incremental run
    would be possible at all.

    [REASON]: `known_md5=None` means "we could not find out" and downloads
    everything, exactly as before. An unreachable manifest must degrade to a
    slow-but-correct run, never to a snapshot with silently missing polygons.
    """
    from drone_collector.geometry import contour_from_node, scrub

    out = logger or log
    sleep = sleep_fn or time.sleep
    counters = GeometryDownloadCounters()
    known = frozenset(str(m).lower() for m in (known_md5 or ()))
    geometries = {}
    sources = [source for source in (contour_from_node(node) for node in nodes)
               if source is not None]
    counters.selected = len(sources)
    for index, source in enumerate(sources, start=1):
        if progress_every and index % progress_every == 0:
            out.info('Geometry %d/%d: known=%d new=%d failed=%d',
                     index, len(sources), counters.known_skipped,
                     counters.downloaded, _geometry_failures(counters))
        if not source.has_link or not source.content_md5:
            counters.no_geometry += 1
            continue
        md5 = str(source.content_md5).lower()
        if md5 in known:
            # Ссылка всё равно снимается: подписанный URL не должен пережить
            # этот цикл ни в узле, ни в памяти.
            source.take_link()
            counters.known_skipped += 1
            continue
        if md5 in geometries:
            source.take_link()
            counters.duplicate_in_run += 1
            continue
        link = source.take_link()
        try:
            blob = download_fn(link)
        except Exception as exc:
            counters.failed += 1
            out.warning('Contour %s did not download (%s)', source.uuid,
                        scrub(exc))
            continue
        finally:
            link = None
        if not isinstance(blob, (bytes, bytearray)) or not blob:
            counters.failed += 1
            out.warning('Contour %s: the download returned an empty body',
                        source.uuid)
            continue
        blob = bytes(blob)
        if len(blob) > max_bytes:
            counters.too_large += 1
            out.warning('Contour %s: %d bytes exceed the cap', source.uuid,
                        len(blob))
            continue
        if hashlib.md5(blob).hexdigest().lower() != md5:
            # [REASON]: a differing md5 is another object or a cut body; a
            # polygon of the wrong field stored under this md5 would be a
            # confident wrong area later.
            counters.md5_mismatch += 1
            out.warning('Contour %s: DJI named a different content md5; '
                        'not kept', source.uuid)
            continue
        if find_secret_markers(blob.decode('utf-8', errors='replace')):
            counters.secret_in_payload += 1
            out.warning('Contour %s: the payload carries a secret marker; '
                        'not kept', source.uuid)
            continue
        counters.downloaded += 1
        counters.bytes += len(blob)
        geometries[md5] = base64.b64encode(blob).decode('ascii')
        if index < len(sources) and pause_s:
            sleep(pause_s)
    out.info('Geometry %d/%d done: known=%d new=%d no-polygon=%d failed=%d',
             len(sources), len(sources), counters.known_skipped,
             counters.downloaded, counters.no_geometry,
             _geometry_failures(counters))
    return geometries, counters


def _geometry_failures(counters):
    """Всё, что НЕ доехало: отказ, чужой md5, перебор размера, секрет."""
    return (counters.failed + counters.md5_mismatch + counters.too_large
            + counters.secret_in_payload)


def snapshot_dry_run_path(out_dir, run_id):
    safe = re.sub(r'[^A-Za-z0-9._-]+', '_', run_id)
    return Path(out_dir) / ('land_snapshot_dry_run_%s.json' % safe)


def write_snapshot_dry_run(bodies, out_dir, run_id):
    """What would have been queued. Checked for secrets before writing."""
    target = snapshot_dry_run_path(out_dir, run_id)
    document = {'dry_run': True, 'nothing_was_queued': True,
                'capture_run_id': run_id, 'chunks': bodies}
    text = json.dumps(document, ensure_ascii=False, indent=1)
    found = find_secret_markers(text)
    if found:
        raise SecretInEnvelope('the dry-run report carries %s; nothing was '
                               'written' % ', '.join(found))
    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open('w', encoding='utf-8') as handle:
        handle.write(text)
    return target


class SnapshotDrainResult(SourceDrainResult):
    """Same shape as the source drain; counters are a LandSnapshotSendResult."""


def snapshot_refusal_reasons(counters, expected_lands, expected_geometries):
    """Why a snapshot chunk was NOT accepted in full. Empty -- accepted."""
    if counters is None:
        return ['the endpoint returned no counters at all']
    reasons = []
    if counters.status != 'ok':
        reasons.append('the endpoint answered status %r' % (counters.status,))
    if not counters.counters_agree:
        reasons.append('the counters do not add up')
    if counters.errors:
        reasons.append('%d land(s) were rejected by the endpoint'
                       % counters.errors)
    if counters.geometries_errors:
        reasons.append('%d geometry(ies) were rejected by the endpoint'
                       % counters.geometries_errors)
    if counters.lands_seen != expected_lands:
        reasons.append('the endpoint saw %d land(s) of the %d that were sent'
                       % (counters.lands_seen, expected_lands))
    if counters.geometries_seen != expected_geometries:
        reasons.append('the endpoint saw %d geometry(ies) of the %d that were '
                       'sent' % (counters.geometries_seen,
                                 expected_geometries))
    return reasons


def drain_land_snapshot_outbox(outbox, cfg, logger, send_fn=None):
    """POST pending snapshot chunks in order; move the accepted to `sent/`.

    Order is by identity -- `<run_id>:<chunk>` -- so an older, unsent
    snapshot goes before a newer one and the `final` chunk of each goes
    last. A refused chunk stops the run with everything after it pending.
    """
    from drone_collector.sender import (LandSnapshotSendResult,
                                        send_land_snapshot_chunk)

    send = send_fn or send_land_snapshot_chunk
    result = SnapshotDrainResult()
    readable = _readable_pending(outbox, KIND_LAND_SNAPSHOT + '_', logger,
                                 result)
    readable.sort(key=lambda pair: str(pair[1].get('identity')))
    result.envelopes = len(readable)
    if not readable:
        logger.info('The snapshot queue holds nothing to send.')
        result.left_pending = len(outbox.pending())
        return result

    total = LandSnapshotSendResult()
    for index, (path, envelope) in enumerate(readable, start=1):
        body = envelope['body']
        counters = send(body, cfg, logger=logger, index=index,
                        total=len(readable))
        result.batches += 1
        if counters is not None:
            total.add(counters.as_dict())
            total.status = counters.status
        refusals = snapshot_refusal_reasons(
            counters, len(body.get('lands') or []),
            len(body.get('geometries') or []))
        if refusals:
            result.accepted = False
            result.refusal_reasons = refusals
            for reason in refusals:
                logger.error('Snapshot chunk %d/%d was NOT fully accepted: '
                             '%s', index, len(readable), reason)
            logger.error('This chunk and %d after it stay in pending/; '
                         'nothing was lost.', len(readable) - index)
            break
        outbox.mark_sent(path)
        result.sent += 1
    result.counters = total
    result.left_pending = len(outbox.pending())
    return result


